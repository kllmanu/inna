// Run with the browser tool's filename option against `npm run dev -- --port 4175`.
// This mocks native XR poses/hits only; A-Frame and application code are real.
(async function (page) {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const reports = [];
  page.on('dialog', dialog => dialog.accept());
  await page.addInitScript(() => {
    const xr = new EventTarget();
    xr.isSessionSupported = async mode => mode === 'immersive-ar';
    Object.defineProperty(navigator, 'xr', { configurable: true, value: xr });
  });
  await page.goto('http://127.0.0.1:4175');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.waitForFunction(() => !document.querySelector('#record').disabled);
  const attachXR = async () => page.evaluate(() => {
    const scene = document.querySelector('a-scene');
    const fake = new EventTarget(), reference = new EventTarget();
    fake.visibilityState = 'visible';
    fake.domOverlayState = { type: 'screen' };
    fake.requestReferenceSpace = async () => reference;
    fake.requestHitTestSource = async () => ({ cancel() {} });
    fake.requestAnimationFrame = callback => { fake.callback = callback; return 1; };
    fake.end = async () => { fake.dispatchEvent(new Event('end')); };
    scene.renderer.xr.getSession = () => fake;
    scene.enterAR = async () => { scene.dispatchEvent(new Event('enter-vr')); };
    window.mockXR = { fake, reference, tracked: true, viewer: { x: 4, y: 1.7, z: 7 }, hit: { x: 4, y: 0, z: 7 } };
    window.stepXR = () => {
      const mock = window.mockXR;
      const pose = position => ({ transform: { position, orientation: { x: 0, y: 0, z: 0, w: 1 } } });
      fake.callback(0, {
        getViewerPose: () => mock.tracked ? pose(mock.viewer) : null,
        getHitTestResults: () => mock.hit ? [{ getPose: () => pose(mock.hit) }] : [],
      });
    };
  });
  const step = async changes => page.evaluate(changes => {
    Object.assign(window.mockXR, changes); window.stepXR();
  }, changes || {});
  await attachXR();
  await page.locator('#track-name').fill('Browser test only');
  await page.locator('#destination').fill('TEST-ROOM');
  await page.locator('#start-spot').fill('Test floor spot at U328');
  await page.locator('#start-facing').fill('Test fixed feature');
  await page.locator('#record').click();
  await page.waitForFunction(() => !!window.mockXR.fake.callback);
  await step();
  await page.locator('#origin').click();
  await step();
  await page.locator('#xr-facing').fill('Edited test facing feature');
  await page.locator('#heading').click();
  await step({ hit: { x: 4, y: 0, z: 5 } });
  await page.locator('#add').click();
  await step({ hit: { x: 4, y: 0, z: 3 } });
  await page.locator('#turn-right').click();
  await step({ tracked: false });
  check(await page.locator('#undo').isDisabled(), 'Tracking loss must disable undo');
  check(await page.locator('#add').isDisabled(), 'Tracking loss must disable capture');
  check(await page.locator('#arrows').getAttribute('visible') === 'false', 'Tracking loss must hide arrows');
  await step({ tracked: true, hit: { x: 7, y: 0, z: 3 } });
  await page.locator('#add').click();
  await step();
  await page.locator('#undo').click();
  await step();
  await page.locator('#finish').click();
  await page.waitForFunction(() => !document.querySelector('#draft-panel').hidden);
  check(await page.locator('#route-select option').count() === 1, 'Capture must not autosave');
  const quotaRestore = await page.evaluate(() => {
    window.originalSetItem = Storage.prototype.setItem;
    Storage.prototype.setItem = () => { throw new DOMException('Test quota', 'QuotaExceededError'); };
    return true;
  });
  check(quotaRestore, 'Quota mock installed');
  await page.locator('#save').click();
  check((await page.locator('#message').textContent()).includes('Could not save'), 'Quota error must be visible');
  check(await page.locator('#export-draft').isEnabled(), 'Export remains available after quota error');
  const downloaded = page.waitForEvent('download');
  await page.locator('#export-draft').click();
  check((await downloaded).suggestedFilename().endsWith('.json'), 'Draft JSON download exists');
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await page.locator('#save').click();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('inna.u328.routes.v1')));
  check(stored.routes.length === 1 && stored.routes[0].points.length === 4, 'Complete capture persisted');
  check(stored.routes[0].instructions.facing === 'Edited test facing feature', 'Edited instructions persist');
  check(stored.routes[0].points[3].x === 3 && stored.routes[0].points[3].z === -4, 'Floor-relative coordinates persist');
  reports.push('Record, edit calibration instructions, tracking loss, undo, finish, quota failure, export and explicit save');
  await page.reload();
  await page.waitForFunction(() => !document.querySelector('#play').disabled);
  await attachXR();
  await page.locator('#play').click();
  await page.waitForFunction(() => !!window.mockXR.fake.callback);
  await step();
  await page.locator('#origin').click();
  await step();
  await page.locator('#heading').click();
  await step();
  check(await page.locator('#arrows > a-entity').count() === 3, 'Only first segment shown');
  check(await page.locator('#advance').isDisabled(), 'Corner far away cannot advance');
  await step({ viewer: { x: 4, y: 1.7, z: 3 } });
  check(await page.locator('#advance').isEnabled(), 'Near corner enables explicit advance');
  check(await page.locator('#arrows > a-entity').count() === 3, 'Proximity must not auto advance');
  await step({ tracked: false });
  check(await page.locator('#advance').isDisabled(), 'Tracking loss disables advancement');
  await step({ tracked: true });
  await page.locator('#advance').click();
  await step();
  check(await page.locator('#arrows > a-entity').count() === 2, 'Only second segment revealed after confirmation');
  check(await page.locator('#advance').isDisabled(), 'Arrival requires destination proximity');
  await step({ viewer: { x: 7, y: 2, z: 3 } });
  await page.locator('#advance').click();
  await step();
  check((await page.locator('#xr-status').textContent()).includes('Arrival confirmed'), 'Arrival explicitly confirmed');
  await page.locator('#xr-exit').click();
  await page.locator('#play').click();
  await step();
  check(await page.locator('#origin').isVisible(), 'New session must reset calibration');
  await page.evaluate(() => window.mockXR.reference.dispatchEvent(new Event('reset')));
  await step();
  check(await page.locator('#origin').isDisabled(), 'Reference-space reset blocks calibration');
  await page.locator('#xr-exit').click();
  await page.locator('#play').click();
  await step();
  await page.evaluate(() => {
    window.mockXR.fake.visibilityState = 'hidden';
    window.mockXR.fake.dispatchEvent(new Event('visibilitychange'));
  });
  await step();
  check(await page.locator('#origin').isDisabled(), 'Visibility interruption blocks controls');
  await page.evaluate(() => { window.mockXR.fake.visibilityState = 'visible'; });
  await step();
  check(await page.locator('#origin').isDisabled(), 'Visibility recovery still requires recalibration in a new session');
  await page.locator('#xr-exit').click();
  await page.evaluate(() => { window.mockXR.fake.domOverlayState = undefined; });
  await page.locator('#play').click();
  await page.waitForFunction(() => document.querySelector('#message').textContent.includes('DOM-overlay controls are unavailable'));
  check(!await page.evaluate(() => document.documentElement.classList.contains('xr-active')), 'Missing mandatory overlay ends the session');
  reports.push('Reload, playback, explicit corner/arrival gating, height independence, calibration reset, reference/visibility interruptions, mandatory DOM overlay');
  const json = JSON.stringify({ version: 1, route: stored.routes[0] });
  await page.locator('#import').setInputFiles({ name: 'track.json', mimeType: 'application/json', buffer: Buffer.from(json) });
  await page.locator('#save').click();
  check(await page.locator('#route-select option').count() === 2, 'Import saves a new copy');
  await page.locator('#import').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"version":2}') });
  check((await page.locator('#message').textContent()).includes('Import failed'), 'Import errors visible');
  await page.locator('#delete').click();
  check(await page.locator('#route-select option').count() === 1, 'Explicit deletion works');
  await page.evaluate(() => localStorage.setItem('inna.u328.routes.v1', '{broken'));
  await page.reload();
  check(await page.locator('#storage-recovery').isVisible(), 'Corrupted storage recovery visible');
  check(await page.evaluate(() => localStorage.getItem('inna.u328.routes.v1')) === '{broken', 'Corrupt storage not overwritten');
  await page.locator('#import').setInputFiles({ name: 'recover.json', mimeType: 'application/json', buffer: Buffer.from(json) });
  check(await page.locator('#save').isDisabled(), 'Corrupt storage blocks save');
  check(await page.locator('#export-draft').isEnabled(), 'Recovered route remains exportable');
  await page.locator('#clear-storage').click();
  await page.locator('#save').click();
  check(await page.evaluate(() => JSON.parse(localStorage.getItem('inna.u328.routes.v1')).routes.length) === 1, 'Explicit recovery allows saving');
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile layout must not overflow');
  reports.push('Import copy, invalid import, delete, corrupt storage protection/recovery and mobile layout');
  await page.evaluate(() => localStorage.removeItem('inna.u328.routes.v1'));
  await page.evaluate(reports => { window.browserCheckReports = reports; }, reports);
  return reports;
})
